<?php
require __DIR__ . '/_lib.php';

// ساخت/ویرایش داخلی روی FreePBX نیازمند بازاعمال کامل (fwconsole reload) است و
// اگر مستقیم در دیتابیس دست ببریم ممکن است پیکربندی ایزابل خراب شود.
// در این فاز ویرایش داخلی از خود ایزابل انجام می‌شود؛ اینجا فقط تأیید نرم می‌دهیم
// تا رابط نشکند. اتصال ایمن ویرایش در فاز بعد با API رسمی FreePBX اضافه می‌شود.
$in = input();
$ext = preg_replace('/\D/', '', (string)($in['ext'] ?? ''));
if (strlen($ext) < 2) fail('شماره داخلی نامعتبر است');

out(['ok' => true, 'note' => 'ویرایش داخلی فعلاً از پنل ایزابل انجام می‌شود']);
